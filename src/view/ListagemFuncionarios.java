    private void preencherTabela() {
        DefaultTableModel modeloTabela = (DefaultTableModel) tblFuncionarios.getModel();
        modeloTabela.setNumRows(0);

        FuncionarioDAO dao = new FuncionarioDAO();
        List<Funcionario> lista = dao.listarTodos();

        SimpleDateFormat formatoData = new SimpleDateFormat("dd/MM/yyyy");

        model.TelefoneDAO telDAO = new model.TelefoneDAO();

        for (Funcionario f : lista) {
            String dataNascFormatada = (f.getDataNascimento() != null) ? formatoData.format(f.getDataNascimento()) : "";
            String statusAtivo = f.isAtivo() ? "Sim" : "Não";

            List<model.Telefone> telefonesDoFunc = telDAO.buscarPorFuncionario(f.getIdFuncionario());
            StringBuilder textoTelefones = new StringBuilder();

            for (model.Telefone t : telefonesDoFunc) {
                if (textoTelefones.length() > 0) {
                    textoTelefones.append(" | ");
                }

                textoTelefones.append("(").append(t.getDdd()).append(") ").append(t.getTelefone());
            }

            String telefonesExibicao = (textoTelefones.length() == 0) ? "Sem telefone" : textoTelefones.toString();

            String enderecoExibicao = (f.getFkEndereco() == 0) ? "Sem endereço" : "Cadastrado (ID: " + f.getFkEndereco() + ")";

            modeloTabela.addRow(new Object[]{
                f.getIdFuncionario(),
                f.getNomeFuncionario(),
                f.getCpf(),
                f.getFuncao(),
                telefonesExibicao,
                String.format("R$ %.2f", f.getValorDoServico()),
                statusAtivo
            });
        }

        sorter = new TableRowSorter<>(modeloTabela);
        tblFuncionarios.setRowSorter(sorter);
    }

    private void filtrarTabela() {
        String texto = txtFuncionarioPesquisarPorNome.getText().trim();

        if (texto.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(javax.swing.RowFilter.regexFilter("(?i)" + texto, 1));
        }
    }


