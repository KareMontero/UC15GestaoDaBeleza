    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linhaSelecionada = tblFuncionarios.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecione um funcionário na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir permanentemente este funcionário?", "Confirmar Exclusão", JOptionPane.YES_NO_OPTION);

        if (confirmacao == JOptionPane.YES_OPTION) {
            try {

                int linhaRealDoModelo = tblFuncionarios.convertRowIndexToModel(linhaSelecionada);
                int idFuncionario = Integer.parseInt(tblFuncionarios.getModel().getValueAt(linhaRealDoModelo, 0).toString());

                FuncionarioDAO dao = new FuncionarioDAO();
                dao.excluir(idFuncionario);

                JOptionPane.showMessageDialog(this, "Funcionário excluído com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);

                preencherTabela();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro ao excluir funcionário:\n" + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

